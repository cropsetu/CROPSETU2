/**
 * Voice-stream cancellation registry.
 *
 * The /ai/voice streaming pipeline runs in the BACKGROUND after the HTTP response
 * is sent, pushing audio chunks over Socket.IO. When the user leaves the voice
 * screen (back / tab switch / end call) the client emits `voice:cancel`; the
 * socket handler flips the flag here, and the pipeline (which checks it between
 * SSE frames and before each TTS/emit) aborts promptly — so it stops generating,
 * stops synthesising, stops emitting, and refunds the credit hold.
 *
 * WHY THIS IS REDIS-BACKED AND NOT JUST A Map
 *   The flag used to live only in a module-level Map. server.js mounts the
 *   Socket.IO Redis adapter, so this deployment is multi-instance: the websocket
 *   carrying `voice:cancel` is very often on a DIFFERENT replica from the one
 *   running the HTTP request's background pipeline. The cancel then flipped a
 *   flag nobody was reading, and the pipeline ran to completion — full Gemini
 *   generation plus a per-sentence Sarvam TTS bill — for a farmer who had already
 *   left the screen. With N replicas the deliberate Back-button cancel silently
 *   no-opped (N-1)/N of the time.
 *
 *   So cancellation is now published to Redis at `voice_cancel:<userId>:<streamId>`
 *   and every registered stream polls for its own marker once a second. The
 *   in-process Map is kept as the same-instance fast path (zero added latency and
 *   still fully functional when Redis is down), and `state.cancelled` stays a
 *   plain synchronous boolean so the pipeline's hot loop does not have to await.
 *
 * Key = `${userId}:${streamId}`. Entries are removed when the pipeline finishes
 * (its finally block), which also clears the timer and the Redis marker, so
 * neither the map nor Redis grows without bound. The TTL is the backstop for the
 * case where the pipeline's instance dies before its finally block runs.
 */
import redis, { isRedisHealthy } from '../config/redis.js';
import logger from '../utils/logger.js';

// Longer than any single voice turn can legitimately run (the SSE read is capped
// at 60s and the TTS tail adds a few more), short enough that an orphaned marker
// from a crashed instance cannot outlive the streamId that would collide with it.
const CANCEL_TTL_SEC = 300;

// One EXISTS per active stream per second. Voice turns are ~5-40s, so this is a
// handful of round-trips per turn — cheap next to the Sarvam TTS call it prevents.
const POLL_INTERVAL_MS = 1_000;

// streamId is client-supplied (`req.body.streamId`), so bound what reaches Redis.
// Truncation is deterministic and applied on every path, so register / cancel /
// unregister always agree on the same key.
const MAX_KEY_LEN = 200;

const registry = new Map(); // key -> { state, timer, warned }

const _norm       = (key) => String(key || '').slice(0, MAX_KEY_LEN);
const _cancelKey  = (key) => `voice_cancel:${key}`;
// Cancelling on socket disconnect has to work without knowing the streamId, so
// each live stream also registers itself under its user.
const _userSetKey = (userId) => `voice_streams:${String(userId || '').slice(0, MAX_KEY_LEN)}`;
const _userOf     = (key) => key.slice(0, key.indexOf(':') === -1 ? key.length : key.indexOf(':'));

/** Flip the local flag for `key` if this instance is the one running that stream. */
function _flipLocal(key) {
  const entry = registry.get(key);
  if (!entry) return false;
  entry.state.cancelled = true;
  return true;
}

/**
 * Publish the cancel marker. SET NX so the first canceller wins and a repeat
 * cancel cannot extend the TTL indefinitely; EX so a marker whose stream never
 * unregisters (instance died) expires on its own.
 */
async function _publishCancel(key) {
  if (!isRedisHealthy()) return false;
  try {
    await redis.set(_cancelKey(key), '1', 'EX', CANCEL_TTL_SEC, 'NX');
    return true;
  } catch (err) {
    logger.warn('[VoiceStream] cancel publish failed for %s: %s', key, err.message);
    return false;
  }
}

export function registerVoiceStream(key) {
  const k = _norm(key);
  // Defensive: a re-register under a live key would otherwise leak the old timer.
  // Only the LOCAL timer is cleared here — deliberately not the Redis marker.
  // streamId is generated by the client and sent in the request body, so a farmer
  // who taps Back while the HTTP request is still in flight can emit voice:cancel
  // BEFORE the pipeline ever registers; clearing the marker here would erase that
  // cancel and run the turn anyway. The initial probe() below picks it up instead.
  const prior = registry.get(k);
  if (prior?.timer) clearInterval(prior.timer);

  const state = { cancelled: false };
  const entry = { state, timer: null, warned: false };
  registry.set(k, entry);

  const probe = async () => {
    if (state.cancelled || !registry.has(k)) return;
    if (!isRedisHealthy()) return;            // in-process Map still covers this instance
    try {
      if (await redis.exists(_cancelKey(k))) {
        state.cancelled = true;
        logger.info('[VoiceStream] cancel observed via Redis for %s', k);
        clearInterval(entry.timer);
      }
    } catch (err) {
      // Once per stream — a per-second warn during a Redis outage would bury the
      // one [ALERT][Redis] line that actually matters.
      if (!entry.warned) {
        entry.warned = true;
        logger.warn('[VoiceStream] cancel poll failed for %s (same-instance cancel still works): %s', k, err.message);
      }
    }
  };

  entry.timer = setInterval(probe, POLL_INTERVAL_MS);
  entry.timer.unref?.();   // never hold the process open on this timer
  probe();                 // catch a cancel that raced ahead of registration

  if (isRedisHealthy()) {
    // Fire-and-forget: the stream is usable before this lands, and losing it only
    // costs the disconnect-sweep (an explicit voice:cancel still carries its own id).
    redis.multi()
      .sadd(_userSetKey(_userOf(k)), k)
      .expire(_userSetKey(_userOf(k)), CANCEL_TTL_SEC)
      .exec()
      .catch(() => {});
  }

  return state;
}

/**
 * Cancel one stream. Flips the local flag (instant on this instance) AND publishes
 * to Redis so the instance actually running the pipeline sees it within one poll.
 *
 * Returns true when the cancellation was recorded somewhere it can be observed.
 * The socket handler ignores the result; it is awaited only by tests.
 */
export async function cancelVoiceStream(key) {
  const k = _norm(key);
  const local = _flipLocal(k);
  const published = await _publishCancel(k);
  return local || published;
}

/**
 * Cancel every live stream belonging to a user — the shape a socket `disconnect`
 * handler needs, because a disconnect never carries a streamId.
 *
 * @returns {Promise<number>} how many distinct streams were cancelled
 */
export async function cancelVoiceStreamsForUser(userId) {
  const prefix = `${String(userId || '')}:`;
  const keys = new Set();
  for (const k of registry.keys()) if (k.startsWith(prefix)) keys.add(k);

  if (isRedisHealthy()) {
    try {
      for (const k of await redis.smembers(_userSetKey(userId))) keys.add(_norm(k));
    } catch (err) {
      logger.warn('[VoiceStream] user stream lookup failed for %s: %s', userId, err.message);
    }
  }

  for (const k of keys) await cancelVoiceStream(k);
  if (keys.size) logger.info('[VoiceStream] cancelled %d stream(s) for user=%s', keys.size, userId);
  return keys.size;
}

export function unregisterVoiceStream(key) {
  const k = _norm(key);
  const entry = registry.get(k);
  if (entry?.timer) clearInterval(entry.timer);
  registry.delete(k);
  if (isRedisHealthy()) {
    redis.multi()
      .del(_cancelKey(k))
      .srem(_userSetKey(_userOf(k)), k)
      .exec()
      .catch(() => {});
  }
}
